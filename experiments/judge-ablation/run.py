#!/usr/bin/env python
"""J0 vs J2: the judge-free ablation, on one fixed recall set per query.

``docs/prototype.md`` §6 makes this a requirement rather than an option, and
``docs/develop/plan.md`` §5.6 explains why it applies to this project literally
rather than theoretically: **AutoScholarQuery's gold was generated by an LLM from
papers' related-work sections.** Ranking with an LLM judge against gold an LLM
produced inflates the judged arm by a shared bias, and the only way to separate
that from a real gain is to report both arms every time.

So the two arms differ in exactly one thing:

    J0   judge_level=off    the recall order the fusion produced
    J2   judge_level=l3b    the same candidates, re-ordered by graded criteria

Both arms hit the same service with the same query, the same date boundary, the
same sources and the same top_k, and the candidate set is recalled once per arm
from the same providers. That leaves the judge as the only difference - which is
what an agent-driven comparison could not give, because two episodes of the same
agent do not issue the same queries.

This is deliberately **not** the end-to-end number. It measures what the judge does
to a ranking, not what an agent does with a judge. The end-to-end path is
``experiments/eval-runner``.

Usage:
  uv run python experiments/judge-ablation/run.py \\
      --queries runs/eval/train-20/queries.json --k 20 --out runs/judge-ablation/train-20
"""

from __future__ import annotations

import argparse
import json
import re
import sys
import time
from pathlib import Path
from typing import Any

import httpx

#: Bumped when this script's recorded shape changes.
ABLATION_VERSION = "1"

_ARXIV_SHAPES = (
    re.compile(r"^(?:arxiv:)?(\d{4}\.\d{4,5})(?:v\d+)?$", re.IGNORECASE),
    re.compile(r"arxiv\.org/(?:abs|pdf)/(\d{4}\.\d{4,5})", re.IGNORECASE),
    re.compile(r"10\.48550/arxiv\.(\d{4}\.\d{4,5})", re.IGNORECASE),
)


def normalize_arxiv(value: Any) -> str | None:
    """One form for every spelling both sides use. Mirrors the JS scorer's rule."""
    if not isinstance(value, str):
        return None
    text = value.strip()
    for pattern in _ARXIV_SHAPES:
        match = pattern.search(text)
        if match:
            return match.group(1).lower()
    return None


def arxiv_ids_of(paper: dict[str, Any]) -> set[str]:
    """The arXiv ids one returned paper denotes.

    A DOI-only paper contributes nothing to an arXiv-id gold. That is a fact about
    the gold, not a bug - and it is reported rather than hidden, because otherwise
    precision would be computed against a denominator that quietly shrank.
    """
    found: set[str] = set()
    for field in ("arxiv_id", "canonical_id", "paper_id", "doi"):
        identifier = normalize_arxiv(paper.get(field))
        if identifier:
            found.add(identifier)
    return found


def score_arm(papers: list[dict[str, Any]], gold: set[str], k: int) -> dict[str, Any]:
    """Recall@k / Precision@k / F1 for one arm, and what could not be credited."""
    top = papers[:k]
    predicted: set[str] = set()
    unscorable = 0
    for paper in top:
        ids = arxiv_ids_of(paper)
        if not ids:
            unscorable += 1
        predicted |= ids
    hits = sorted(gold & predicted)
    # The ranked ids, in order. Without them "J0 and J2 scored the same" cannot be
    # told from "the judge changed nothing", and those are different findings.
    order = [
        next(iter(sorted(arxiv_ids_of(paper))), paper.get("canonical_id") or paper.get("paper_id")) for paper in top
    ]
    recall = len(hits) / len(gold) if gold else None
    precision = len(hits) / len(predicted) if predicted else 0.0
    f1 = 0.0 if recall is None else (0.0 if recall + precision == 0 else 2 * recall * precision / (recall + precision))
    return {
        "returned": len(papers),
        "scored_top_k": len(top),
        "predicted": len(predicted),
        "unscorable_predictions": unscorable,
        "order": order,
        "hits": hits,
        "missed": sorted(gold - predicted),
        "recall": recall,
        "precision": precision,
        "f1": None if recall is None else f1,
    }


def search_text(item: dict[str, Any]) -> str:
    """What to actually send to the service.

    ``searchQuery`` overrides ``query`` when present, and the record keeps both.
    The reason it exists: this ablation needs a recall set that *contains* gold, or
    both arms score zero and the comparison says nothing about the judge. Sending
    the dataset's question verbatim does not produce one - it is a 17-word sentence,
    and the service AND-joins terms (F-1's fix), so it recalls almost nothing.

    Substituting the query is legitimate **here** and nowhere else: what this
    experiment varies is the judge, holding the candidate set fixed, so the query
    is a fixture. The end-to-end number, where the agent writes its own queries, is
    ``experiments/eval-runner``'s job.
    """
    return str(item.get("searchQuery") or item["query"])


def run_arm(client: httpx.Client, base_url: str, item: dict[str, Any], level: str, k: int) -> dict[str, Any]:
    """One arm of one query. A failed call is recorded, never dropped."""
    body: dict[str, Any] = {"query": search_text(item), "top_k": k, "judge_level": level}
    if item.get("endDate"):
        body["end_date"] = item["endDate"]
    if item.get("sources"):
        body["sources"] = item["sources"]

    started = time.perf_counter()
    try:
        response = client.post(f"{base_url}/search/metadata", json=body, timeout=600.0)
    except httpx.HTTPError as exc:
        return {
            "level": level,
            "ok": False,
            "error": str(exc),
            "elapsed_ms": int((time.perf_counter() - started) * 1000),
        }
    elapsed_ms = int((time.perf_counter() - started) * 1000)
    if response.status_code != 200:
        return {
            "level": level,
            "ok": False,
            "error": f"HTTP {response.status_code}: {response.text[:400]}",
            "elapsed_ms": elapsed_ms,
        }

    payload = response.json()
    state = payload.get("search_state") or {}
    return {
        "level": level,
        "ok": True,
        "elapsed_ms": elapsed_ms,
        "papers": payload.get("papers") or [],
        # The whole judge account, so a stored run says which instrument produced it.
        "judge": state.get("judge") or {},
        "failures": state.get("failures") or [],
    }


def mean(values: list[float | None]) -> float | None:
    usable = [value for value in values if isinstance(value, (int, float))]
    return sum(usable) / len(usable) if usable else None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--queries", required=True, help="queries file from experiments/eval-runner/autoscholarquery.mjs"
    )
    parser.add_argument("--base-url", default="http://127.0.0.1:8000")
    parser.add_argument("--k", type=int, default=20)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--out", default=None, help="directory for ablation.json")
    args = parser.parse_args()

    items = json.loads(Path(args.queries).read_text(encoding="utf-8"))
    if args.limit is not None:
        items = items[: args.limit]
    if not items:
        parser.error("the queries file is empty")

    results: list[dict[str, Any]] = []
    with httpx.Client(trust_env=False) as client:
        for item in items:
            gold = {
                identifier
                for identifier in map(normalize_arxiv, item.get("gold", {}).get("arxivIds", []))
                if identifier
            }
            record: dict[str, Any] = {
                "id": item.get("id"),
                "query": item.get("query"),
                # Recorded separately when the fixture overrode it, so nobody reads
                # these numbers as "the dataset's question scored this".
                "search_query": search_text(item),
                "gold": sorted(gold),
                "arms": {},
            }
            for level in ("off", "l3b"):
                arm = run_arm(client, args.base_url, item, level, args.k)
                scored = score_arm(arm.get("papers", []), gold, args.k) if arm["ok"] else None
                record["arms"]["J0" if level == "off" else "J2"] = {
                    **{key: value for key, value in arm.items() if key != "papers"},
                    "score": scored,
                }
            results.append(record)
            j0 = record["arms"]["J0"].get("score") or {}
            j2 = record["arms"]["J2"].get("score") or {}
            print(
                f"{record['id']}: J0 recall {j0.get('recall')} | J2 recall {j2.get('recall')} | "
                f"judged {record['arms']['J2'].get('judge', {}).get('judged')}",
                flush=True,
            )

    report = {
        "ablationVersion": ABLATION_VERSION,
        "k": args.k,
        "baseUrl": args.base_url,
        "queries": len(results),
        "macro": {
            arm: {
                "recall": mean(
                    [
                        r["arms"][arm].get("score", {}).get("recall") if r["arms"][arm].get("score") else None
                        for r in results
                    ]
                ),
                "precision": mean(
                    [
                        r["arms"][arm].get("score", {}).get("precision") if r["arms"][arm].get("score") else None
                        for r in results
                    ]
                ),
                "f1": mean(
                    [
                        r["arms"][arm].get("score", {}).get("f1") if r["arms"][arm].get("score") else None
                        for r in results
                    ]
                ),
                "median_elapsed_ms": sorted(r["arms"][arm]["elapsed_ms"] for r in results)[len(results) // 2],
            }
            for arm in ("J0", "J2")
        },
        "results": results,
    }

    print()
    for arm in ("J0", "J2"):
        macro = report["macro"][arm]
        show = lambda value: "n/a" if value is None else f"{value:.4f}"  # noqa: E731
        print(
            f"{arm}: Recall@{args.k} {show(macro['recall'])} | Precision@{args.k} {show(macro['precision'])} "
            f"| F1 {show(macro['f1'])} | median {macro['median_elapsed_ms']}ms"
        )
    print(
        "\nBoth arms are reported together on purpose: AutoScholarQuery's gold is LLM-generated, so any J2 gain "
        "carries a shared-bias component that a judged-only number would hide (prototype.md §6)."
    )

    if args.out:
        out_dir = Path(args.out)
        out_dir.mkdir(parents=True, exist_ok=True)
        path = out_dir / "ablation.json"
        path.write_text(f"{json.dumps(report, indent=2)}\n", encoding="utf-8")
        print(f"written: {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
